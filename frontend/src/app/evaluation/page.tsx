'use client'

import { useState } from 'react'
import { PrecisionRecallChart, ScoreSeparationChart } from '@/components/charts/charts'
import {
  AlertIcon,
  Badge,
  Button,
  Cell,
  CheckIcon,
  CrossIcon,
  EmptyState,
  ErrorState,
  GaugeIcon,
  GlassPanel,
  KeyValue,
  Panel,
  Row,
  SectionHeader,
  Skeleton,
  StatTile,
  Table,
} from '@/components/ui/primitives'
import { ApiError, api } from '@/lib/api'
import { useApi } from '@/lib/hooks'
import {
  formatCost,
  formatDateTime,
  formatDuration,
  formatMillis,
  formatNumber,
  formatRatio,
  formatTokens,
} from '@/lib/format'
import type { EvaluationMetrics, EvaluationRun } from '@/lib/types'

export default function EvaluationPage() {
  const [running, setRunning] = useState(false)
  const [error, setError] = useState<ApiError | null>(null)
  const latest = useApi((signal) => api.latestEvaluation(signal), [])

  async function run() {
    setRunning(true)
    setError(null)
    try {
      await api.runEvaluation({ name: 'ui-triggered-evaluation', sample_size: 800, retrieval_sample: 25 })
      latest.refresh()
    } catch (caught) {
      setError(caught instanceof ApiError ? caught : new ApiError(0, 'unexpected_error', String(caught)))
    } finally {
      setRunning(false)
    }
  }

  const evaluation = latest.data
  const metrics = (evaluation?.metrics ?? null) as EvaluationMetrics | null
  const hasMetrics = Boolean(metrics && metrics.ranking)

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <div className="mb-1.5 font-mono text-[10px] font-medium uppercase tracking-[0.14em] text-ink-muted">
            Measurement
          </div>
          <h1 className="text-[26px] font-semibold tracking-[-0.025em] text-ink">Evaluation</h1>
          <p className="mt-1.5 max-w-3xl text-[13px] text-ink-secondary">
            Measures what the system actually does against the historical outcomes it never sees: how well
            the risk model ranks churn, whether retrieval stays inside the right account, and how the
            workflow behaves under load.
          </p>
        </div>
        <Button variant="primary" loading={running} onClick={run} icon={<GaugeIcon className="h-4 w-4" />}>
          {running ? 'Running evaluation…' : 'Run evaluation'}
        </Button>
      </div>

      {error ? <ErrorState error={error} /> : null}
      {latest.error ? <ErrorState error={latest.error} onRetry={latest.refresh} /> : null}

      <GlassPanel className="px-4 py-3">
        <p className="flex items-start gap-2 text-[12.5px] leading-snug text-ink-secondary">
          <AlertIcon className="mt-0.5 h-3.5 w-3.5 shrink-0 text-[color-mix(in_srgb,var(--status-warning)_85%,var(--ink))]" />
          <span>
            Every number on this page is computed from the synthetic dataset generated by this repository.
            They measure the implementation, not real-world churn prediction. The risk model is a
            transparent weighted heuristic — it was never fitted on data.
          </span>
        </p>
      </GlassPanel>

      {latest.initialLoading ? (
        <div className="space-y-3">
          <Skeleton className="h-24 rounded-card" />
          <Skeleton className="h-64 rounded-card" />
        </div>
      ) : !evaluation ? (
        <Panel>
          <EmptyState
            icon={<GaugeIcon />}
            title="No evaluation has been run yet"
            description="The harness scores every labelled customer with the deterministic risk model, compares the ranking against the real outcome, probes semantic retrieval, and summarises the workflow runs that have executed."
            action={
              <Button variant="primary" size="sm" loading={running} onClick={run}>
                Run the evaluation
              </Button>
            }
          />
        </Panel>
      ) : !hasMetrics || !metrics ? (
        <Panel className="p-4">
          <SectionHeader eyebrow={evaluation.status} title={evaluation.name} />
          <p className="mt-2 text-[13px] text-ink-secondary">
            {evaluation.error_message ?? 'This evaluation produced no metrics.'}
          </p>
        </Panel>
      ) : (
        <EvaluationResults evaluation={evaluation} metrics={metrics} />
      )}
    </div>
  )
}

function EvaluationResults({
  evaluation,
  metrics,
}: {
  evaluation: EvaluationRun
  metrics: EvaluationMetrics
}) {
  const ranking = metrics.ranking
  const retrieval = metrics.retrieval
  const workflow = metrics.workflow
  const dataset = metrics.dataset

  const atK = Object.entries(ranking.at_k ?? {}).map(([k, value]) => ({
    k,
    precision: value.precision,
    recall: value.recall,
  }))

  const claims = (workflow.claims ?? {}) as Record<string, number>
  const reports = (workflow.reports ?? {}) as Record<string, number | boolean>
  const integrityOk = reports.report_integrity_ok === true
  const leaked = Number(reports.rejected_claims_leaked_into_reports ?? 0)

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-center gap-x-4 gap-y-1 font-mono text-[11px] text-ink-muted">
        <span>{evaluation.name}</span>
        <Badge tone={evaluation.status === 'COMPLETED' ? 'good' : 'warning'}>{evaluation.status}</Badge>
        <span>{formatDateTime(evaluation.created_at)}</span>
        <span>computed in {formatMillis(evaluation.duration_ms)}</span>
      </div>

      {/* Ranking headline */}
      <section>
        <SectionHeader
          eyebrow="Ranking quality"
          title="Can the risk model find the accounts that actually churned?"
          description={`Scored against ${formatNumber(dataset.labelled_customers)} customers with a known historical outcome — a label the risk engine never reads. Each account is scored as of its own outcome date, so the model only ever sees pre-outcome behaviour.`}
        />
        <div className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          <StatTile
            label="ROC-AUC"
            value={ranking.roc_auc === null || ranking.roc_auc === undefined ? '—' : ranking.roc_auc.toFixed(3)}
            hint="0.5 is a coin flip, 1.0 is perfect"
            tone={(ranking.roc_auc ?? 0) > 0.7 ? 'good' : 'neutral'}
            emphasis
          />
          <StatTile
            label="Average precision"
            value={
              ranking.average_precision === null || ranking.average_precision === undefined
                ? '—'
                : ranking.average_precision.toFixed(3)
            }
            hint={`base rate ${formatRatio(dataset.base_rate ?? null)}`}
            emphasis
          />
          <StatTile
            label="Churn base rate"
            value={formatRatio(dataset.base_rate ?? null)}
            hint={`${formatNumber(dataset.positive_outcomes ?? 0)} churned/downgraded of ${formatNumber(dataset.labelled_customers)}`}
            emphasis
          />
          <StatTile
            label="Lift at top 5%"
            value={
              ranking.at_percentile?.['5%']?.lift === null ||
              ranking.at_percentile?.['5%']?.lift === undefined
                ? '—'
                : `${ranking.at_percentile['5%'].lift.toFixed(2)}×`
            }
            hint="versus picking accounts at random"
            tone={(ranking.at_percentile?.['5%']?.lift ?? 0) > 2 ? 'good' : 'neutral'}
            emphasis
          />
        </div>
      </section>

      <div className="grid gap-4 lg:grid-cols-2">
        <PrecisionRecallChart rows={atK} />
        <ScoreSeparationChart
          positive={ranking.mean_score_positive ?? null}
          negative={ranking.mean_score_negative ?? null}
        />
      </div>

      {ranking.at_percentile ? (
        <Panel>
          <div className="border-b border-[var(--line)] px-4 py-3">
            <SectionHeader
              eyebrow="Ranking"
              title="Precision, recall and lift by percentile"
              description="How a customer-success team would actually use this: work the top slice of the ranking."
            />
          </div>
          <Table head={['Top slice', 'Accounts', 'Precision', 'Recall', 'Lift vs random']}>
            {Object.entries(ranking.at_percentile).map(([percentile, value]) => (
              <Row key={percentile}>
                <Cell mono>{percentile}</Cell>
                <Cell numeric>{formatNumber(value.k)}</Cell>
                <Cell numeric>{formatRatio(value.precision, 1)}</Cell>
                <Cell numeric>{value.recall === null ? '—' : formatRatio(value.recall, 1)}</Cell>
                <Cell numeric className="font-medium text-ink">
                  {value.lift === null ? '—' : `${value.lift.toFixed(2)}×`}
                </Cell>
              </Row>
            ))}
          </Table>
        </Panel>
      ) : null}

      {/* Retrieval */}
      <section>
        <SectionHeader
          eyebrow="Retrieval quality"
          title="Does semantic search return the right account's documents?"
          description={retrieval.metric_note}
        />
        {retrieval.note ? (
          <Panel className="mt-3 p-4">
            <p className="text-[13px] text-ink-secondary">{retrieval.note}</p>
          </Panel>
        ) : (
          <div className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
            <StatTile
              label="Customer scope precision"
              value={formatRatio(retrieval.customer_scope_precision ?? null)}
              hint={
                retrieval.customer_scope_precision === 1
                  ? 'no cross-account leakage — this must be exactly 100%'
                  : 'BELOW 100% — the customer filter leaked'
              }
              tone={retrieval.customer_scope_precision === 1 ? 'good' : 'critical'}
              icon={retrieval.customer_scope_precision === 1 ? <CheckIcon className="h-3.5 w-3.5" /> : <CrossIcon className="h-3.5 w-3.5" />}
              emphasis
            />
            <StatTile
              label="Risk-relevant chunks"
              value={formatRatio(retrieval.risk_relevant_chunk_rate ?? null)}
              hint="keyword-overlap proxy, not human-judged"
              emphasis
            />
            <StatTile
              label="Accounts with a signal"
              value={formatRatio(retrieval.accounts_with_risk_signal_rate ?? null)}
              hint={`${formatNumber(retrieval.accounts_sampled ?? 0)} churned accounts sampled`}
              emphasis
            />
            <StatTile
              label="Embedding provider"
              value={<span className="text-[18px]">{retrieval.embedding_provider ?? '—'}</span>}
              hint={
                retrieval.embedding_provider === 'local'
                  ? `deterministic hashed embeddings · mean cosine ${(retrieval.mean_relevance_score ?? 0).toFixed(3)}`
                  : 'live embedding model'
              }
            />
          </div>
        )}
      </section>

      {/* Workflow */}
      <section>
        <SectionHeader
          eyebrow="Workflow quality"
          title="How the orchestration behaved"
          description="Measured from the runs that have actually executed in this environment."
        />
        {workflow.note ? (
          <Panel className="mt-3 p-4">
            <p className="text-[13px] text-ink-secondary">{workflow.note}</p>
          </Panel>
        ) : (
          <>
            <div className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
              <StatTile
                label="Completion rate"
                value={formatRatio(workflow.completion_rate ?? null)}
                hint={`${formatNumber(workflow.runs_completed ?? 0)} of ${formatNumber(workflow.runs_total ?? 0)} runs`}
                tone={(workflow.completion_rate ?? 0) === 1 ? 'good' : 'neutral'}
                emphasis
              />
              <StatTile
                label="Avg run duration"
                value={formatDuration(workflow.avg_duration_seconds ?? null)}
                hint={`P95 ${formatDuration(workflow.p95_duration_seconds ?? null)}`}
                emphasis
              />
              <StatTile
                label="Retry recovery"
                value={
                  workflow.retry_recovery_rate === null || workflow.retry_recovery_rate === undefined
                    ? 'n/a'
                    : formatRatio(workflow.retry_recovery_rate)
                }
                hint={`${formatNumber(workflow.tasks_retried ?? 0)} task${workflow.tasks_retried === 1 ? '' : 's'} retried`}
                tone={(workflow.retry_recovery_rate ?? 1) === 1 ? 'good' : 'warning'}
                emphasis
              />
              <StatTile
                label="Estimated cost"
                value={formatCost(workflow.estimated_cost_usd ?? null)}
                hint={`${formatNumber(workflow.llm_calls ?? 0)} calls · ${formatTokens(workflow.total_tokens ?? 0)} tokens`}
                emphasis
              />
            </div>

            <div className="mt-4 grid gap-4 lg:grid-cols-2">
              <Panel className="p-4">
                <SectionHeader eyebrow="Hallucination mitigation" title="Claim quality" />
                <dl className="mt-2">
                  <KeyValue label="Material claims" value={formatNumber(claims.total ?? 0)} />
                  <KeyValue
                    label="Claims with valid evidence"
                    value={formatRatio(claims.claims_with_valid_evidence_rate ?? null)}
                  />
                  <KeyValue label="Supported" value={formatRatio(claims.supported_rate ?? null)} />
                  <KeyValue
                    label="Partially supported"
                    value={formatRatio(claims.partially_supported_rate ?? null)}
                  />
                  <KeyValue label="Rejected" value={formatRatio(claims.rejected_rate ?? null)} />
                  <KeyValue
                    label="Unsupported before verification"
                    value={formatRatio(claims.unsupported_before_verification_rate ?? null)}
                  />
                  <KeyValue
                    label="Unsupported after verification"
                    value={
                      <span className="text-[var(--status-good)]">
                        {formatRatio(claims.unsupported_after_verification_rate ?? 0)}
                      </span>
                    }
                  />
                </dl>
                <p className="mt-2.5 border-t border-[var(--line)] pt-2 text-[11.5px] leading-snug text-ink-muted">
                  The first figure is what the investigator produced on its own; the second is what survived
                  into the reports. The gap between them is the verification stage doing its job.
                </p>
              </Panel>

              <Panel className="p-4">
                <SectionHeader eyebrow="Integrity" title="Report check" />
                <div
                  className={
                    integrityOk
                      ? 'mt-3 flex items-start gap-3 rounded-card border border-[color-mix(in_srgb,var(--status-good)_32%,transparent)] bg-[color-mix(in_srgb,var(--status-good)_8%,transparent)] p-3'
                      : 'mt-3 flex items-start gap-3 rounded-card border border-[color-mix(in_srgb,var(--status-critical)_32%,transparent)] bg-[color-mix(in_srgb,var(--status-critical)_8%,transparent)] p-3'
                  }
                >
                  {integrityOk ? (
                    <CheckIcon className="mt-0.5 h-4 w-4 shrink-0 text-[var(--status-good)]" />
                  ) : (
                    <CrossIcon className="mt-0.5 h-4 w-4 shrink-0 text-[var(--status-critical)]" />
                  )}
                  <div>
                    <p className="text-[13px] font-medium text-ink">
                      {integrityOk
                        ? 'No rejected claim appears as a conclusion in any report'
                        : `${leaked} rejected claim${leaked === 1 ? '' : 's'} leaked into a report`}
                    </p>
                    <p className="mt-1 text-[12px] leading-snug text-ink-secondary">
                      Every conclusion across{' '}
                      {formatNumber(Number(reports.total ?? 0))} report
                      {Number(reports.total ?? 0) === 1 ? '' : 's'} (
                      {formatNumber(Number(reports.verified_conclusions ?? 0))} statements) was cross-checked
                      against the set of claims verification rejected.
                    </p>
                  </div>
                </div>
                <dl className="mt-3">
                  <KeyValue label="Tasks executed" value={formatNumber(workflow.tasks_total ?? 0)} />
                  <KeyValue label="Tasks failed" value={formatNumber(workflow.tasks_failed ?? 0)} />
                  <KeyValue
                    label="Invalid structured outputs"
                    value={formatNumber(workflow.invalid_structured_outputs ?? 0)}
                  />
                  <KeyValue
                    label="Avg LLM latency"
                    value={formatMillis(workflow.avg_llm_latency_ms ?? null)}
                  />
                  <KeyValue
                    label="Avg tokens per call"
                    value={formatNumber(workflow.avg_tokens_per_call ?? null)}
                  />
                </dl>
              </Panel>
            </div>
          </>
        )}
      </section>

      {/* Model card */}
      <Panel className="p-4">
        <SectionHeader
          eyebrow="Model card"
          title="What the risk score is"
          description={`${metrics.model.type.replace(/_/g, ' ')} — not a trained predictive model.`}
        />
        <div className="mt-3 grid gap-x-8 gap-y-1 sm:grid-cols-2">
          {Object.entries(metrics.model.weights).map(([key, weight]) => (
            <div
              key={key}
              className="flex items-baseline justify-between gap-3 border-b border-[var(--line)] py-1.5"
            >
              <span className="text-[12px] capitalize text-ink-secondary">{key.replace(/_/g, ' ')}</span>
              <span className="font-mono text-[12px] tabular-nums text-ink">{(weight * 100).toFixed(0)}%</span>
            </div>
          ))}
        </div>
        <p className="mt-3 text-[11.5px] leading-snug text-ink-muted">{metrics.caveat}</p>
      </Panel>
    </div>
  )
}
